"""Points the training worlds at the sharper ground texture:

    python3 tools/sharpen_terrain.py            # apply
    python3 tools/sharpen_terrain.py --dry-run  # show the change
    python3 tools/sharpen_terrain.py --revert   # put the backups back

WHAT IT CHANGES, AND THE ARITHMETIC
-----------------------------------
Every world painted its terrain with grass_diffuse.png across a 40 m tile:

    256 px / 40 m = 6.4 pixels per metre

The chase camera sits 9 m from the aircraft, so the ground beside it was
being magnified about fifteen times. That is why the picture stayed soft
after the camera itself went to 1600x900 - the camera was faithfully
reproducing a blurry surface.

    ground_fine.png, 1024 px / 16 m = 64 pixels per metre

Ten times the detail. The texture is generated by
tools/make_ground_texture.py rather than downloaded, so it is reproducible
from this repository and does not depend on a server being reachable.

WHY 16 m AND NOT SMALLER
------------------------
A 16 m tile repeats about a thousand times across a 16 km terrain. Smaller
tiles are sharper still but repeat more, and a repeat that becomes visible
from altitude is worse than slightly softer ground up close. The texture is
fine uniform grain for the same reason: it hides its own repeat, where
anything with a large feature in it would announce it.

SAFETY
------
Same as the other world tools: PX4's copies are edited (nothing tracks
them), this repository's copies carry the change as committed content, every
file is backed up to <name>.sdf.pretexture first, the result is parsed as
XML, and anything that fails to parse is restored automatically.
"""
import os
import re
import shutil
import sys
import xml.etree.ElementTree as ET

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)
import sim_target                                            # noqa: E402

PX4_WORLDS = os.path.expanduser("~/PX4-Autopilot/Tools/simulation/gz/worlds")
REPO_WORLDS = os.path.join(REPO, "sim", "worlds")
SUFFIX = ".pretexture"

TEXTURE = "ground_fine.png"
OLD_DIFFUSE = "file://media/grass_diffuse.png"
NEW_DIFFUSE = "file://media/" + TEXTURE
TILE_M = 16


def world_paths():
    """Each training world once, from the copy the simulator actually loads."""
    found = []
    for env in sim_target.ENVIRONMENTS:
        name = env["world"] + ".sdf"
        px4 = os.path.join(PX4_WORLDS, name)
        repo = os.path.join(REPO_WORLDS, name)
        if os.path.isfile(px4):
            found.append(px4)
        elif os.path.isfile(repo):
            found.append(repo)
    return found


def install_texture(directory):
    source = os.path.join(REPO_WORLDS, "media", TEXTURE)
    target_dir = os.path.join(directory, "media")
    if not os.path.isfile(source) or os.path.abspath(target_dir) == \
            os.path.abspath(os.path.join(REPO_WORLDS, "media")):
        return False
    os.makedirs(target_dir, exist_ok=True)
    # Always overwrite: a stale texture fails silently and looks like the
    # change not having worked.
    shutil.copy2(source, os.path.join(target_dir, TEXTURE))
    return True


def retexture(text):
    """Returns (new_text, changed). Only the heightmap's own texture block is
    touched - the <size> that carries the terrain's real extent in metres
    lives in a different element and must not be rewritten."""
    if NEW_DIFFUSE in text:
        return text, False
    if OLD_DIFFUSE not in text:
        return text, False
    out = text.replace(OLD_DIFFUSE, NEW_DIFFUSE)
    # The tile size is the <size> inside <texture>, which on these worlds is
    # the only bare single-number <size> in the file.
    out, count = re.subn(r"<size>\s*40\s*</size>", "<size>%d</size>" % TILE_M, out)
    return out, count > 0


def revert():
    restored = 0
    for path in world_paths():
        backup = path + SUFFIX
        if os.path.exists(backup):
            shutil.copy2(backup, path)
            print("restored %s" % os.path.basename(path))
            restored += 1
    print("\n%d file(s) restored." % restored if restored else
          "\nNo %s backups found - nothing to restore." % SUFFIX)
    return 0


def apply(dry_run):
    paths = world_paths()
    if not paths:
        print("No training worlds found.", file=sys.stderr)
        return 1

    edited = skipped = failed = 0
    for path in paths:
        name = os.path.basename(path)
        with open(path) as handle:
            text = handle.read()
        new_text, changed = retexture(text)
        if not changed:
            print("SKIP  %s: already sharpened, or no grass texture to replace"
                  % name)
            skipped += 1
            continue
        if dry_run:
            print("WOULD EDIT %s: %s at a %d m tile (%s)"
                  % (name, TEXTURE, TILE_M, os.path.dirname(path)))
            edited += 1
            continue

        backup = path + SUFFIX
        if not os.path.exists(backup):
            shutil.copy2(path, backup)
        with open(path, "w") as handle:
            handle.write(new_text)
        try:
            ET.parse(path)
        except ET.ParseError as exc:
            shutil.copy2(backup, path)
            print("FAIL  %s: XML broke (%s) - reverted" % (name, exc),
                  file=sys.stderr)
            failed += 1
            continue
        installed = install_texture(os.path.dirname(path))
        print("OK    %s: %d m tile, %d px/m%s"
              % (name, TILE_M, 1024 // TILE_M,
                 "\n        texture copied beside it" if installed else ""))
        edited += 1

    print()
    print("edited=%d skipped=%d failed=%d" % (edited, skipped, failed))
    if dry_run:
        print("\nDry run - nothing written.")
    elif edited and not failed:
        print("\nRestart the simulator for it to take effect.")
    return 1 if failed else 0


def main(argv):
    if "--revert" in argv:
        return revert()
    return apply("--dry-run" in argv)


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except BrokenPipeError:
        try:
            sys.stdout.close()
        except BrokenPipeError:
            pass
        sys.exit(0)
