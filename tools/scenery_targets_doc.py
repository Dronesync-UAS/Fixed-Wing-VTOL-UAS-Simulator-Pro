"""Regenerates docs/scenery-targets.md from scenery.py:

    python3 tools/scenery_targets_doc.py

The instructor's notes on what is in each training area, and where the
three payload targets are, have to agree with the world files. The only
way to be sure of that is to generate them from the same source the
world files are generated from, which is scenery.py. Edit that, then run
this.
"""
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)
import scenery                                              # noqa: E402
import sim_target                                           # noqa: E402

OUT = os.path.join(REPO, "docs", "scenery-targets.md")

HEAD = """# Payload targets, and what is in each training area

GENERATED by `tools/scenery_targets_doc.py` from `scenery.py`, which is
where the layouts live. Do not edit this file by hand - change
`scenery.py` and run the tool again.

## The three marked targets

Every area carries the same three targets, at the same bearings and
ranges from the launch point. That is deliberate: a student moving from
the desert to the fens should be practising reading a different
landscape, not learning three new positions.

They are chequered panels six metres wide and just over three metres
tall, with an orange drum at the foot and one to three orange tabs
across the top. The tabs are the number, and they are only readable
zoomed in - which is the point of the exercise.

| Target | Bearing from launch | Range | North (m) | East (m) |
|---|---|---|---|---|
"""

MIDDLE = """
Target 3 at 700 m is **outside the station's 500 m range limit**. That is
on purpose: it can be found and identified with the gimbal from inside
the limit, which is the lesson. Flying out to it is a limit breach, and
the flight log will say how long for.

## What is in each area
"""

TAIL = """## The rules the layouts follow

* **Nothing within %(clear)g m of the launch point.** That is where the
  aircraft spawns, arms, hovers and lands.
* **Buildings and masts have collision; vegetation does not.** An
  obstacle an aircraft can fly through teaches a student that obstacles
  do not matter. A tree with collision at 25 m/s is a crash with no
  lesson in it and a lot of contact solving.
* **The layout is the same every time.** It is generated from the
  world's own name with a fixed generator, so "the orange container
  north-east of the hangar" still means something next week.
* **Primitives only** - boxes, cylinders, spheres, ellipsoids. No mesh
  files to install, nothing for Gazebo's resource path to fail to find.

## What has not been done

None of this has been loaded in Gazebo. The geometry parses as XML and
the layout is checked by `tools/test_scenery.py`, but nobody has looked
at it, and nobody has measured what it costs in frame rate.
"""


def build():
    lines = [HEAD]
    for t in scenery.target_positions():
        lines.append("| %d | %03d deg | %g m | %+.0f | %+.0f |\n"
                     % (t["number"], t["bearing_deg"], t["range_m"],
                        t["north_m"], t["east_m"]))
    lines.append(MIDDLE)
    for env in sim_target.ENVIRONMENTS:
        world = env["world"]
        theme = scenery.WORLD_THEMES.get(world)
        lines.append("\n### %s\n\n" % env["label"])
        if theme is None:
            lines.append("`%s` - deliberately bare, so there is always one "
                         "world with nothing in it to isolate a fault "
                         "against.\n" % world)
            continue
        items = scenery.layout(world)
        lines.append("`%s`, theme `%s`: %d features built from %d shapes.\n"
                     % (world, theme, len(items),
                        sum(len(p[3]) for p in items)))
        lines.append("\n%s\n" % _describe(theme))
    lines.append("\n")
    lines.append(TAIL % {"clear": scenery.CLEAR_RADIUS_M})
    return "".join(lines)


def _describe(theme):
    """The one-line summary from scenery.py's own docstring for the theme."""
    doc = (scenery.THEMES[theme].__doc__ or "").strip().splitlines()
    return doc[0] if doc else ""


def main():
    text = build()
    with open(OUT, "w") as handle:
        handle.write(text)
    print("Wrote %s (%d lines)" % (OUT, text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
